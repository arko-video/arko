describe('fbank 80 « Kaldi »', () => {
  const x = signalFabrique();

  it.each(Object.keys(OPTIONS) as (keyof typeof OPTIONS)[])('%s : identique à la référence à 1e-4 près', (nom) => {
    const ref = REFERENCE[nom];
    const r = fbank80(x, OPTIONS[nom]);
    expect(r.trames).toBe(ref.trames);
    expect(r.donnees.length).toBe(ref.trames * FBANK.bandes);
    let ecart = 0;
    for (const [t, ligne] of Object.entries(ref.lignes)) {
      const k = Number(t);
      for (let b = 0; b < 80; b++) ecart = Math.max(ecart, Math.abs(r.donnees[k * 80 + b]! - ligne[b]!));
    }
    expect(ecart).toBeLessThan(1e-4);
    let somme = 0;
    let carres = 0;
    for (const v of r.donnees) {
      somme += v;
      carres += v * v;
    }
    expect(Math.abs(somme - ref.somme)).toBeLessThan(1e-3 * Math.max(1, Math.abs(ref.somme)) + 0.05);
    expect(Math.abs(carres - ref.carres) / ref.carres).toBeLessThan(1e-5);
  });

  it('CMN : chaque bande a une moyenne nulle ; moins de 25 ms : aucune trame', () => {
    const r = fbank80(x);
    for (const b of [0, 40, 79]) {
      let s = 0;
      for (let t = 0; t < r.trames; t++) s += r.donnees[t * 80 + b]!;
      expect(Math.abs(s / r.trames)).toBeLessThan(1e-5);
    }
    expect(fbank80(new Float32Array(399)).trames).toBe(0);
    expect(fbank80(new Float32Array(400)).trames).toBe(1);
    expect(fbank80(new Float32Array(16000)).trames).toBe(98);
  });

  it('silence : plancher du log, sans NaN', () => {
    const r = fbank80(new Float32Array(2000), { cmn: false });
    expect(r.donnees.every((v) => Number.isFinite(v) && Math.abs(v - Math.log(1.1920928955078125e-7)) < 1e-5)).toBe(true);
  });
});
